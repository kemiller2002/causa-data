module Causa.Everyday.Tests

open System
open System.IO
open Xunit
open IndyInitRootCauseInvestigator.Engine
open Causa.Contract
open Causa.Tool

let private repoRoot =
    let rec up (directory: DirectoryInfo) =
        if File.Exists(Path.Combine(directory.FullName, "engine.lock.json")) then directory.FullName
        else up (directory.Parent |> nonNull)
    up (DirectoryInfo(AppContext.BaseDirectory))

let private schemas =
    Store.loadSchemas (Layout.schemas repoRoot)
    |> Result.defaultWith (fun error -> failwith error.Detail)

let private build outcome =
    Everyday.build schemas outcome
    |> Result.defaultWith failwith

[<Fact>]
let ``everyday investigation is deterministic replayable and preserves competing reasoning`` () =
    let first = build Everyday.Outcome.Illuminates
    let second = build Everyday.Outcome.Illuminates
    Assert.Equal(Everyday.investigationId, first.Files.DirectoryId)
    Assert.Equal<byte>(first.Files.Manifest, second.Files.Manifest)
    Assert.Equal<byte>(first.Files.Events, second.Files.Events)
    Assert.Equal<byte>(first.Files.Snapshot, second.Files.Snapshot)
    let replayed =
        Store.validate schemas first.Files
        |> Result.defaultWith (fun error -> failwith error.Detail)
    Assert.Equal(first.Loaded.StateSha256, replayed.StateSha256)
    let hypotheses = first.Loaded.State.Hypotheses |> Map.toList |> List.map snd
    Assert.Equal(4, hypotheses.Length)
    Assert.Single(hypotheses |> List.filter (fun hypothesis -> hypothesis.State = Supported)) |> ignore
    Assert.Equal(3, hypotheses |> List.filter (fun hypothesis -> hypothesis.State = Weakened) |> List.length)
    Assert.Contains(hypotheses, fun hypothesis -> hypothesis.Statement.Value = "The bulb has failed." && hypothesis.State = Supported)
    Assert.Contains(first.Loaded.State.Relationships |> Map.toList |> List.map snd,
                    fun relationship -> relationship.Kind = Supports && first.Loaded.State.Hypotheses[relationship.Hypothesis].Statement.Value = "The bulb has failed.")
    let conclusion = first.Loaded.State.Conclusions |> Map.toList |> List.map snd |> List.exactlyOne
    Assert.Equal(ConfirmedCause, conclusion.Strength)
    Assert.Contains("exact internal failure mechanism", conclusion.ResidualUncertainty.Value.Value)

[<Fact>]
let ``corrective action is completed before fresh verification and a contradictory outcome fails closed`` () =
    let success = build Everyday.Outcome.Illuminates
    let indexed = success.Run.Events |> List.indexed
    let index predicate = indexed |> List.find (snd >> _.Body >> predicate) |> fst
    let proposed = index (function CorrectiveActionRecorded _ -> true | _ -> false)
    let implemented = index (function CorrectiveActionTransitioned(_, Implemented) -> true | _ -> false)
    let awaiting = index (function CorrectiveActionTransitioned(_, AwaitingVerificationOfEffect) -> true | _ -> false)
    let verified = index (function VerificationRecorded(_, _, Satisfied, _) -> true | _ -> false)
    Assert.True(proposed < implemented && implemented < awaiting && awaiting < verified)
    let correction = success.Loaded.State.CorrectiveActions |> Map.toList |> List.map snd |> List.exactlyOne
    Assert.Equal("Replace the failed bulb with a compatible replacement.", correction.Description.Value)
    Assert.Equal(VerifiedEffective, correction.State)

    let negative = build Everyday.Outcome.RemainsDark
    let negativeCorrection = negative.Loaded.State.CorrectiveActions |> Map.toList |> List.map snd |> List.exactlyOne
    Assert.Equal(VerificationFailed, negativeCorrection.State)
    Assert.Empty(negative.Loaded.State.Conclusions)
    Assert.DoesNotContain(negative.Loaded.State.Causes |> Map.toList |> List.map snd, fun cause -> cause.State = CauseConfirmed)
    Assert.Contains(negative.Run.Refusals, fun (_, code, _) -> code = "CAUSE.MEMBER_NOT_SUPPORTED")

[<Fact>]
let ``committed everyday storage is generated by the supported domain script`` () =
    let generated = build Everyday.Outcome.Illuminates
    let directory = Everyday.canonicalDirectory repoRoot
    let committed = Store.readDirectory directory |> Result.defaultWith (fun error -> failwith error.Detail)
    Assert.Equal<byte>(generated.Files.Manifest, committed.Manifest)
    Assert.Equal<byte>(generated.Files.Events, committed.Events)
    Assert.Equal<byte>(generated.Files.Snapshot, committed.Snapshot)
